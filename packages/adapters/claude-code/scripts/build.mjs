// Bundle the adapter CLI into one ESM file that hooks run with plain `node`.
// `typescript` stays external (resolved from this package's node_modules at runtime) so
// the bundle stays small and hooks that do not analyze code never load the compiler.
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(dirname(fileURLToPath(import.meta.url)));
await build({
  // demo-coordinator is the local coordinator scripts/demo-firm-claim.sh runs (not shipped in the CLI)
  entryPoints: { "weft-claude": join(here, "src/cli.ts"), "demo-coordinator": join(here, "scripts/demo-coordinator.ts") },
  outdir: join(here, "dist"),
  outExtension: { ".js": ".mjs" },
  chunkNames: "chunks/[name]-[hash]",
  splitting: true,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["typescript"],
  banner: { js: "// @weft/adapter-claude-code — generated by scripts/build.mjs; do not edit." },
  logLevel: "warning",
});
