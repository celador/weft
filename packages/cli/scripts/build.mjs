// Build the publishable `@celador/weft` package into dist/:
//   dist/weft.mjs              the CLI (src/main.ts, bundled)
//   dist/adapters/<harness>/   each adapter's own dist (built by its build script), copied whole
//   dist/gateway/index.js      the gateway Worker bundle (for `weft deploy` and `weft --local`)
// `typescript` is the only runtime dependency; the adapters load it for symbol analysis.
import { build } from "esbuild";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(dirname(fileURLToPath(import.meta.url)));
const root = join(here, "..", "..");
const dist = join(here, "dist");
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));

export const ADAPTERS = {
  "claude-code": "weft-claude.mjs",
  codex: "weft-codex.mjs",
  copilot: "weft-copilot.mjs",
  cursor: "weft-cursor.mjs",
  gemini: "weft-gemini.mjs",
  opencode: "weft-opencode.mjs",
  watcher: "weft-watch.mjs",
};

function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, stdio: ["ignore", "inherit", "inherit"], env: { ...process.env, CLOUDFLARE_API_TOKEN: "" } });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(" ")} failed in ${cwd}`);
}

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// 1. adapters
for (const [name, entry] of Object.entries(ADAPTERS)) {
  const dir = join(root, "packages/adapters", name);
  run(process.execPath, [join(dir, "scripts/build.mjs")], dir);
  if (!existsSync(join(dir, "dist", entry))) throw new Error(`adapter ${name}: dist/${entry} missing after build`);
  cpSync(join(dir, "dist"), join(dist, "adapters", name), { recursive: true });
}
// The tree-sitter grammars (~21 MB) are identical in every adapter's dist. Keep ONE copy in
// dist/adapters/grammars: @weft/analyzer's findGrammar() searches ../grammars from the bundle
// and ../../grammars from dist/chunks, so every adapter finds it there.
const shared = join(dist, "adapters", "grammars");
for (const name of Object.keys(ADAPTERS)) {
  const g = join(dist, "adapters", name, "grammars");
  if (!existsSync(g)) continue;
  if (!existsSync(shared)) cpSync(g, shared, { recursive: true });
  rmSync(g, { recursive: true, force: true });
}

// 2. gateway Worker bundle, exactly what wrangler would upload
const gw = join(root, "apps/gateway");
const out = join(dist, "gateway");
run(process.execPath, [join(root, "node_modules/wrangler/bin/wrangler.js"), "deploy", "--env", "test", "--dry-run", "--outdir", out, "--config", join(gw, "wrangler.toml")], gw);
if (!existsSync(join(out, "index.js"))) throw new Error("gateway bundle missing (dist/gateway/index.js)");
for (const f of ["README.md"]) rmSync(join(out, f), { force: true });

// 3. the CLI
await build({
  entryPoints: { weft: join(here, "src/main.ts") },
  outdir: dist,
  outExtension: { ".js": ".mjs" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  define: { __WEFT_VERSION__: JSON.stringify(pkg.version) },
  banner: { js: "#!/usr/bin/env node\n// @celador/weft — generated by packages/cli/scripts/build.mjs; do not edit." },
  logLevel: "warning",
});
writeFileSync(join(dist, "manifest.json"), JSON.stringify({ version: pkg.version, adapters: ADAPTERS }, null, 2) + "\n");
// npm ships LICENSE from the package directory
cpSync(join(root, "LICENSE"), join(here, "LICENSE"));
