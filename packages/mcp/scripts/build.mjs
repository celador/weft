// Bundle the MCP server into one ESM file (dist/weft-mcp.mjs) that runs with plain `node`.
// The shared WCP core (packages/adapters/claude-code/src), the watcher and the MCP SDK are
// bundled in; `typescript` stays external and is loaded lazily only to analyze code.
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(dirname(fileURLToPath(import.meta.url)));
await build({
  entryPoints: { "weft-mcp": join(here, "src/cli.ts") },
  outdir: join(here, "dist"),
  outExtension: { ".js": ".mjs" },
  chunkNames: "chunks/[name]-[hash]",
  splitting: true,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["typescript"],
  banner: { js: "// @weft/mcp — generated by scripts/build.mjs; do not edit.\nimport { createRequire as __weftCreateRequire } from 'node:module'; const require = __weftCreateRequire(import.meta.url);" },
  logLevel: "warning",
});
